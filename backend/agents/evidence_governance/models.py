"""
JARVIS OS — Phase 77: Autonomous Evidence Verification & Engineering Claims Governance
Module: models.py
Domain models, enums, exceptions, and data structures for typed engineering claims,
evidence provenance, verification results, and governance enforcement.
"""

from __future__ import annotations

import enum
import time
import uuid
from dataclasses import asdict, dataclass, field
from typing import Any, Dict, List, Optional, Set, Tuple


class ClaimType(str, enum.Enum):
    """Categories of engineering claims asserted across JARVIS OS operations."""
    REPOSITORY_STATE = "REPOSITORY_STATE"            # File modifications, additions, deletions, git commit states
    SOURCE_INTEGRATION = "SOURCE_INTEGRATION"        # AST symbols exist, type signatures, interfaces match
    TEST_EXECUTION = "TEST_EXECUTION"                # Test suite executed, explicit pass count, zero failures
    PERFORMANCE_BENCHMARK = "PERFORMANCE_BENCHMARK"  # Measured improvement against comparable baseline
    SECURITY_GOVERNANCE = "SECURITY_GOVERNANCE"      # Authorization token present, Sentinel policies satisfied
    PREDICTIVE_CALIBRATION = "PREDICTIVE_CALIBRATION"# Holdout error reduction, calibration version promoted
    RECOVERY_ROLLBACK = "RECOVERY_ROLLBACK"          # Rollback executed, working tree restored cleanly
    PHASE_COMPLETION = "PHASE_COMPLETION"            # All phase acceptance criteria verified


class EvidenceCategory(str, enum.Enum):
    """Categories of evidence supporting an engineering claim."""
    DIRECT_EXECUTION_OUTPUT = "DIRECT_EXECUTION_OUTPUT" # Raw stdout/stderr and process exit codes
    TEST_RUNNER_RESULT = "TEST_RUNNER_RESULT"           # Pytest execution ledger, passed/failed counts
    GIT_REVISION_RECORD = "GIT_REVISION_RECORD"         # Git commit SHA, diff hunks, status list
    AST_INSPECTION_PROOF = "AST_INSPECTION_PROOF"       # Parsed AST nodes and symbol signatures
    BENCHMARK_MEASUREMENT = "BENCHMARK_MEASUREMENT"     # Empirical metrics with documented baseline
    HUMAN_APPROVAL_RECORD = "HUMAN_APPROVAL_RECORD"     # Cryptographic token, reviewer ID, timestamp
    SYNTHETIC_FIXTURE_EVIDENCE = "SYNTHETIC_FIXTURE"    # Explicitly labeled synthetic benchmark fixture
    MODEL_GENERATED_EXPLANATION = "MODEL_EXPLANATION"   # Unverified narrative text generated by model


class EvidenceOriginType(str, enum.Enum):
    """The origin and environmental fidelity of an evidence artifact."""
    REAL_EXECUTION = "REAL_EXECUTION"                # Executed on actual repository code and environment
    SYNTHETIC_FIXTURE = "SYNTHETIC_FIXTURE"          # Generated via controlled test fixture / synthetic data
    STATIC_INSPECTION = "STATIC_INSPECTION"          # Inferred from code inspection without execution
    HUMAN_APPROVAL = "HUMAN_APPROVAL"                # Attested by human authority
    DERIVED_CALCULATION = "DERIVED_CALCULATION"      # Deterministically calculated from existing evidence


class VerificationStatus(str, enum.Enum):
    """Evaluation status of a claim against authoritative evidence."""
    VERIFIED = "VERIFIED"                      # Sufficient valid evidence supports the claim
    PARTIALLY_VERIFIED = "PARTIALLY_VERIFIED"  # Some elements supported; material requirements unmet
    UNVERIFIED = "UNVERIFIED"                  # Required evidence is missing or unexamined
    CONTRADICTED = "CONTRADICTED"              # Authoritative evidence disproves the claim
    STALE = "STALE"                            # Previously valid, but invalidated by code/environment change
    INCONCLUSIVE = "INCONCLUSIVE"              # Conflicting or insufficient evidence


class AssuranceTier(str, enum.Enum):
    """Impact and risk tier governing verification requirements."""
    TIER_1_INFORMATIONAL = "TIER_1_INFORMATIONAL"    # Low risk; descriptive narrative, soft verification
    TIER_2_OPERATIONAL = "TIER_2_OPERATIONAL"        # Intermediate risk; task execution; requires logs
    TIER_3_ARCHITECTURAL = "TIER_3_ARCHITECTURAL"    # High risk; refactoring; requires test proof & diffs
    TIER_4_MISSION_CRITICAL = "TIER_4_MISSION_CRITICAL" # Highest risk; release/production; requires token + diffs + test proof


# --- Exceptions ---

class EvidenceGovernanceError(Exception):
    """Base exception for evidence verification and claims governance."""
    pass


class InvalidEvidenceIntegrityError(EvidenceGovernanceError):
    """Raised when evidence content hash does not match payload or is corrupted."""
    pass


class ContradictoryEvidenceError(EvidenceGovernanceError):
    """Raised when trustworthy evidence directly contradicts an asserted claim."""
    pass


class StaleEvidenceError(EvidenceGovernanceError):
    """Raised when evidence is invalidated by underlying code or environment changes."""
    pass


class UnauthorizedPromotionError(EvidenceGovernanceError):
    """Raised when an unverified or contradicted claim attempts to be promoted to release/completion."""
    pass


class InconclusiveEvidenceError(EvidenceGovernanceError):
    """Raised when two authoritative sources conflict and cannot be deterministically reconciled."""
    pass


# --- Domain Data Structures ---

@dataclass
class EvidenceArtifact:
    """
    Immutable, content-hashed evidence item supporting or refuting engineering claims.
    """
    artifact_id: str
    category: EvidenceCategory
    origin_type: EvidenceOriginType
    content_hash: str                        # SHA-256 over serialized payload
    commit_sha: str                          # Git commit SHA at capture time
    payload: Dict[str, Any]
    source_subsystem: str
    created_at: float = field(default_factory=time.time)
    metadata: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "artifact_id": self.artifact_id,
            "category": self.category.value,
            "origin_type": self.origin_type.value,
            "content_hash": self.content_hash,
            "commit_sha": self.commit_sha,
            "payload": self.payload,
            "source_subsystem": self.source_subsystem,
            "created_at": self.created_at,
            "metadata": self.metadata,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> EvidenceArtifact:
        d = dict(data)
        d["category"] = EvidenceCategory(d["category"])
        d["origin_type"] = EvidenceOriginType(d["origin_type"])
        return cls(**d)


@dataclass
class VerificationResult:
    """The result of verifying an engineering claim against evidence."""
    status: VerificationStatus
    verified_at: float = field(default_factory=time.time)
    verifier_identity: str = "ClaimToEvidenceVerifier"
    explanation: str = ""
    supporting_evidence_ids: List[str] = field(default_factory=list)
    missing_evidence_categories: List[EvidenceCategory] = field(default_factory=list)
    discrepancies: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "status": self.status.value,
            "verified_at": self.verified_at,
            "verifier_identity": self.verifier_identity,
            "explanation": self.explanation,
            "supporting_evidence_ids": self.supporting_evidence_ids,
            "missing_evidence_categories": [c.value for c in self.missing_evidence_categories],
            "discrepancies": self.discrepancies,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> VerificationResult:
        d = dict(data)
        d["status"] = VerificationStatus(d["status"])
        d["missing_evidence_categories"] = [
            EvidenceCategory(c) for c in d.get("missing_evidence_categories", [])
        ]
        return cls(**d)


@dataclass
class EngineeringClaim:
    """
    Structured representation of an engineering claim asserted by JARVIS or its subsystems.
    """
    claim_id: str
    claim_type: ClaimType
    proposition: str
    assurance_tier: AssuranceTier
    originating_subsystem: str
    required_evidence_categories: List[EvidenceCategory]
    evidence_refs: List[str] = field(default_factory=list)
    status: VerificationStatus = VerificationStatus.UNVERIFIED
    verification_result: Optional[VerificationResult] = None
    dependency_files: List[str] = field(default_factory=list)
    commit_sha: Optional[str] = None
    created_at: float = field(default_factory=time.time)
    verified_at: Optional[float] = None
    limitations: str = ""
    notes: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return {
            "claim_id": self.claim_id,
            "claim_type": self.claim_type.value,
            "proposition": self.proposition,
            "assurance_tier": self.assurance_tier.value,
            "originating_subsystem": self.originating_subsystem,
            "required_evidence_categories": [c.value for c in self.required_evidence_categories],
            "evidence_refs": self.evidence_refs,
            "status": self.status.value,
            "verification_result": self.verification_result.to_dict() if self.verification_result else None,
            "dependency_files": self.dependency_files,
            "commit_sha": self.commit_sha,
            "created_at": self.created_at,
            "verified_at": self.verified_at,
            "limitations": self.limitations,
            "notes": self.notes,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> EngineeringClaim:
        d = dict(data)
        d["claim_type"] = ClaimType(d["claim_type"])
        d["assurance_tier"] = AssuranceTier(d["assurance_tier"])
        d["required_evidence_categories"] = [
            EvidenceCategory(c) for c in d.get("required_evidence_categories", [])
        ]
        d["status"] = VerificationStatus(d["status"])
        if d.get("verification_result"):
            d["verification_result"] = VerificationResult.from_dict(d["verification_result"])
        return cls(**d)


@dataclass
class ContradictionRecord:
    """Audit record capturing conflicting evidence or incompatible claims."""
    contradiction_id: str
    claim_id: str
    conflicting_evidence_ids: List[str]
    description: str
    detected_at: float = field(default_factory=time.time)
    resolved: bool = False
    resolution_strategy: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class ReportAuditResult:
    """Summary of auditing a completion report against ground-truth evidence."""
    report_path: str
    total_claims: int
    verified_count: int
    unverified_count: int
    contradicted_count: int
    stale_count: int
    claims_details: List[Dict[str, Any]]
    is_acceptable: bool
    rejection_reasons: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)
